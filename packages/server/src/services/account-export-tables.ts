import { PgDialect } from 'drizzle-orm/pg-core';
import { sql } from 'drizzle-orm';
import { orgAllows } from './access.js';

/**
 * The containers this person owns AND may still reach as an owner (`access.ts`: in a team
 * org that takes an active, non-guest membership). Ownership alone is not a reason to hand
 * over what other people have written there since: somebody who left an organization keeps
 * no claim on its agents, topics, dashboards or radars' settings. Rendered from the one
 * SQL form of the organization term, so the export cannot drift from the lookup.
 */
const ownerReach = (orgColumn: string) =>
  new PgDialect().sqlToQuery(orgAllows(sql.raw(orgColumn), sql.raw('$1'), 'owner')).sql;
const owned = (table: string) =>
  `SELECT id FROM ${table} WHERE owner_id = $1 AND ${ownerReach(`${table}.organization_id`)}`;
const OWNED_RADARS = owned('radars');
const OWNED_TOPICS = owned('topics');
const OWNED_DASHBOARDS = owned('dashboards');
const OWNED_AGENTS = owned('agents');

